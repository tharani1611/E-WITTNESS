"""Repository for AI candidate violence segments (Phases 66 & 69).

Enforces:
- Strict department-scoped isolation on candidate segment queries.
- Monotonic state updates for human review workflow.
- Idempotent retry cleanup preserving reviewed segments.
- Retention-based purging of expired candidate segments while respecting legal holds.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime
from uuid import UUID

from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.core.ai import SegmentReviewStatus
from backend.app.models.ai import AICandidateSegment


class AICandidateSegmentRepository:
    """Persistence operations for AI-detected candidate video segments."""

    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    async def create(self, segment: AICandidateSegment) -> AICandidateSegment:
        """Persist a single candidate segment."""
        self._session.add(segment)
        await self._session.flush()
        return segment

    async def bulk_create(self, segments: list[AICandidateSegment]) -> list[AICandidateSegment]:
        """Persist multiple candidate segments."""
        if not segments:
            return []
        self._session.add_all(segments)
        await self._session.flush()
        return segments

    async def get_by_id(
        self,
        segment_id: UUID,
        *,
        department_id: UUID | None = None,
    ) -> AICandidateSegment | None:
        """Fetch a candidate segment by ID, optionally scoped to department."""
        stmt = select(AICandidateSegment).where(AICandidateSegment.id == segment_id)
        if department_id is not None:
            stmt = stmt.where(AICandidateSegment.department_id == department_id)
        result = await self._session.execute(stmt)
        return result.scalar_one_or_none()

    async def list_for_job(
        self,
        job_id: UUID,
        *,
        department_id: UUID | None = None,
    ) -> Sequence[AICandidateSegment]:
        """List all candidate segments generated by a specific analysis job."""
        stmt = (
            select(AICandidateSegment)
            .where(AICandidateSegment.job_id == job_id)
            .order_by(AICandidateSegment.start_seconds.asc())
        )
        if department_id is not None:
            stmt = stmt.where(AICandidateSegment.department_id == department_id)
        result = await self._session.execute(stmt)
        return result.scalars().all()

    async def list_for_incident(
        self,
        incident_id: UUID,
        *,
        department_id: UUID | None = None,
    ) -> Sequence[AICandidateSegment]:
        """List candidate segments associated with a parent incident report."""
        stmt = (
            select(AICandidateSegment)
            .where(AICandidateSegment.incident_id == incident_id)
            .order_by(AICandidateSegment.created_at.desc(), AICandidateSegment.start_seconds.asc())
        )
        if department_id is not None:
            stmt = stmt.where(AICandidateSegment.department_id == department_id)
        result = await self._session.execute(stmt)
        return result.scalars().all()

    async def list_segments(
        self,
        *,
        department_id: UUID | None = None,
        review_status: str | None = None,
        is_flagged: bool | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> tuple[Sequence[AICandidateSegment], int]:
        """List candidate segments with pagination, department scoping, and status filters."""
        base_query = select(AICandidateSegment)
        count_query = select(func.count()).select_from(AICandidateSegment)

        if department_id is not None:
            base_query = base_query.where(AICandidateSegment.department_id == department_id)
            count_query = count_query.where(AICandidateSegment.department_id == department_id)

        if review_status is not None:
            base_query = base_query.where(AICandidateSegment.review_status == review_status)
            count_query = count_query.where(AICandidateSegment.review_status == review_status)

        if is_flagged is not None:
            base_query = base_query.where(AICandidateSegment.is_flagged_for_review == is_flagged)
            count_query = count_query.where(AICandidateSegment.is_flagged_for_review == is_flagged)

        base_query = (
            base_query.order_by(AICandidateSegment.created_at.desc()).limit(limit).offset(offset)
        )

        total = await self._session.scalar(count_query) or 0
        result = await self._session.execute(base_query)
        items = result.scalars().all()

        return items, total

    async def update(self, segment: AICandidateSegment) -> AICandidateSegment:
        """Flush changes to an existing candidate segment."""
        await self._session.flush()
        return segment

    async def delete_unreviewed_for_job(self, job_id: UUID) -> int:
        """Idempotently delete unreviewed candidate segments for a job retry."""
        stmt = delete(AICandidateSegment).where(
            AICandidateSegment.job_id == job_id,
            AICandidateSegment.review_status == SegmentReviewStatus.PENDING_REVIEW.value,
        )
        result = await self._session.execute(stmt)
        await self._session.flush()
        rowcount = getattr(result, "rowcount", 0)
        return int(rowcount or 0)

    async def purge_expired(
        self,
        *,
        cutoff_date: datetime,
        department_id: UUID | None = None,
        exempt_incident_ids: set[UUID] | None = None,
    ) -> int:
        """Purge candidate segments created before cutoff_date, exempting protected incidents."""
        stmt = delete(AICandidateSegment).where(
            AICandidateSegment.created_at < cutoff_date,
        )
        if department_id is not None:
            stmt = stmt.where(AICandidateSegment.department_id == department_id)
        if exempt_incident_ids:
            stmt = stmt.where(AICandidateSegment.incident_id.not_in(exempt_incident_ids))

        result = await self._session.execute(stmt)
        await self._session.flush()
        rowcount = getattr(result, "rowcount", 0)
        return int(rowcount or 0)
